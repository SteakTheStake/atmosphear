/* Actual Godot native UI + scene-backed locomotion in the exported browser game. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');

(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('Blocking on the main thread'))errors.push(m.text());});
  await page.addInitScript(()=>{
    const pads=[];
    Object.defineProperty(navigator,'getGamepads',{value:()=>pads});
    window.padConnect=()=>{
      const pad={id:'Atmosphear native UI test pad',index:0,connected:true,mapping:'standard',timestamp:performance.now(),axes:[0,0,0,0],buttons:Array.from({length:17},()=>({pressed:false,touched:false,value:0}))};
      pads[0]=pad;const event=new Event('gamepadconnected');Object.defineProperty(event,'gamepad',{value:pad});window.dispatchEvent(event);
    };
    window.padButton=(index,pressed)=>{pads[0].buttons[index]={pressed,touched:pressed,value:pressed?1:0};pads[0].timestamp=performance.now();};
    window.padAxis=(index,value)=>{pads[0].axes[index]=value;pads[0].timestamp=performance.now();};
  });
  const state=()=>page.evaluate(()=>window.atmoDebug);
  const until=(fn,arg=null)=>page.waitForFunction(fn,arg,{timeout:20000});
  const key=async(value)=>{await page.keyboard.press(value,{delay:85});await page.waitForTimeout(200);};
  const hold=async(value,ms)=>{await page.keyboard.down(value);await page.waitForTimeout(ms);await page.keyboard.up(value);await page.waitForTimeout(350);};
  const pad=async(index)=>{await page.evaluate(i=>window.padButton(i,true),index);await page.waitForTimeout(100);await page.evaluate(i=>window.padButton(i,false),index);await page.waitForTimeout(250);};
  fs.mkdirSync('test-results',{recursive:true});fs.writeFileSync('test-results/.gdignore','');
  const result={};
  try{
    await page.goto('http://127.0.0.1:8060/?debug=1');
    await until(()=>window.atmoDebug?.ready&&typeof window.atmoDebug.ui_screen==='string');
    if(await page.locator('#debug').count())await page.locator('#debug').evaluate(e=>e.style.display='none');
    const launch=page.locator('button#launch,button#start');
    if(await launch.count())await launch.first().click();
    await until(()=>window.atmoDebug.ui_screen==='main');
    assert.equal((await state()).started,false,'Launch should lead to a native main menu');
    await page.screenshot({path:'test-results/native-main.png'});
    await key('ArrowDown');await key('Enter');await until(()=>window.atmoDebug.ui_screen==='legacy');await key('Enter');
    await until(()=>window.atmoDebug.started&&window.atmoDebug.ui_screen==='playing'&&window.atmoDebug.level==='forest');
    let initial=await state();
    assert(initial.scene_source.endsWith('forest.tscn'),'Forest must load from an editable scene');
    assert.equal(initial.map_visible,true,'Static environment plan should be visible in normal play');
    assert(!('voices' in initial),'There must be no narration system');
    await page.screenshot({path:'test-results/native-plan.png'});
    const mapSignature=initial.map_signature;
    assert(mapSignature!==undefined,'Map signature must be exposed for regression checks');
    await hold('w',1500);const moved=await state();
    assert(moved.position[1]<initial.position[1]-1);
    assert(moved.steps>=2&&moved.last_step_clip);
    assert.equal(moved.map_signature,mapSignature,'Map data must not follow the player');
    await key('m');await until(()=>!window.atmoDebug.map_visible);
    const unmappedBefore=await state();
    await hold('w',900);const unmappedAfter=await state();
    assert(unmappedAfter.position[1]<unmappedBefore.position[1]-.7,'Exploration must work with the plan hidden');
    assert(unmappedAfter.steps>unmappedBefore.steps,'Hidden-plan walking must keep its footstep feedback');
    assert.equal(unmappedAfter.map_signature,mapSignature);
    await page.screenshot({path:'test-results/native-unmapped.png'});
    await key('m');await until(()=>window.atmoDebug.map_visible);
    await page.keyboard.down('Shift');await page.keyboard.down('w');
    await until(()=>window.atmoDebug.locomotion==='run');
    await page.waitForTimeout(700);await page.keyboard.up('w');await page.keyboard.up('Shift');
    await page.waitForTimeout(400);
    const jumpsBefore=(await state()).jumps;
    await page.keyboard.down('Space');await until(before=>window.atmoDebug.jumps===before+1&&!window.atmoDebug.on_floor,jumpsBefore);
    const airborne=await state();await page.waitForTimeout(180);const stillAir=await state();
    if(!stillAir.on_floor)assert.equal(stillAir.steps,airborne.steps,'No walking footsteps while airborne');
    await page.waitForTimeout(1600);await page.keyboard.up('Space');
    assert.equal((await state()).jumps,jumpsBefore+1,'Holding jump must not chain jumps');
    const punchesBefore=(await state()).punches;await key('e');await until(before=>window.atmoDebug.punches===before+1,punchesBefore);
    result.forest=await state();
    await key('Escape');await until(()=>window.atmoDebug.paused&&window.atmoDebug.ui_screen==='pause');
    // Native button navigation: Resume, Settings, Change environment, Restart, Main menu.
    await key('ArrowDown');await key('Enter');await until(()=>window.atmoDebug.ui_screen==='settings');
    const volume=(await state()).settings.master;
    await key('ArrowLeft');await until(before=>window.atmoDebug.settings.master<before,volume);
    await page.screenshot({path:'test-results/native-settings.png'});
    await key('Escape');await until(()=>window.atmoDebug.ui_screen==='pause');
    await key('ArrowDown');await key('ArrowDown');await key('Enter');await until(()=>window.atmoDebug.ui_screen==='main');
    await key('ArrowDown');await key('Enter');await until(()=>window.atmoDebug.ui_screen==='legacy');await key('ArrowDown');await key('Enter');await until(()=>window.atmoDebug.started&&!window.atmoDebug.paused&&window.atmoDebug.level==='cistern');
    assert((await state()).scene_source.endsWith('cistern.tscn'));
    result.cistern=await state();
    await page.evaluate(()=>window.padConnect());await until(()=>window.atmoDebug.controllers===1);
    await page.evaluate(()=>window.padAxis(1,-1));await page.waitForTimeout(600);await page.evaluate(()=>window.padAxis(1,0));
    await pad(9);await until(()=>window.atmoDebug.paused);
    await pad(0);await until(()=>!window.atmoDebug.paused);
    const controllerJumps=(await state()).jumps;await pad(0);await until(before=>window.atmoDebug.jumps===before+1,controllerJumps);
    await page.waitForTimeout(1200);const controllerPunches=(await state()).punches;
    await pad(2);await until(before=>window.atmoDebug.punches===before+1,controllerPunches);
    await pad(3);await until(()=>!window.atmoDebug.map_visible);
    await pad(3);await until(()=>window.atmoDebug.map_visible);
    await pad(9);await until(()=>window.atmoDebug.paused);
    await pad(13);await pad(0);await until(()=>window.atmoDebug.ui_screen==='settings');
    const padVolume=(await state()).settings.master;
    await pad(14);await until(before=>window.atmoDebug.settings.master<before,padVolume);
    await pad(1);await until(()=>window.atmoDebug.ui_screen==='pause');
    await pad(0);await until(()=>!window.atmoDebug.paused);
    result.controller=await state();
    const savedMaster=result.controller.settings.master;
    await page.waitForTimeout(1200);
    await page.reload();await until(()=>window.atmoDebug?.ready&&window.atmoDebug.ui_screen==='main');
    assert.equal((await state()).settings.master,savedMaster,'Settings should persist after a browser reload');
    result.reloaded=await state();
    assert.deepEqual(errors,[]);
    result.result='PASS: native Godot menus/settings and persistence, editable scenes, static map, walking/running, jump edge handling, no airborne footfalls, punch input, and controller navigation/actions';
    fs.writeFileSync('test-results/experience-browser.json',JSON.stringify(result,null,2));
    console.log(result.result);
  }catch(error){await page.screenshot({path:'test-results/experience-failure.png'});console.error('STATE',JSON.stringify(await state(),null,2));console.error('ERRORS',errors);throw error;}
  finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
